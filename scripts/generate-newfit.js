import { readdir, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// Regenerates src/lib/data/newfitAvatars.ts — two avatar manifests:
// - NEWFIT_AVATARS: slugs with an alternate "-newfit" avatar (new-skin
//   outfit). getAvatar() consults it so it only requests a -newfit.webp for
//   characters that actually have one, instead of requesting it for everyone
//   and 404ing on the ~115 that don't.
// - AVAILABLE_AVATARS: slugs with a base avatar at all. SSR'd pages (Team
//   Builder grid) consult it via hasAvatar() to render an initials
//   placeholder instead of an <img> that 404s — runtime onerror fallbacks
//   can't run during prerender, and the prerenderer treats crawled asset
//   404s as fatal (travelers have no avatar assets).
//
// Auto-run by the predev/prebuild npm hooks, so dropping the three new-skin
// files into static/assets/characters/{full,circle,side}/ is enough — the
// manifest self-updates. Can also be run manually: npm run generate-newfit.

const PROJECT_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
// New-skin avatars are always authored as a full {full,circle,side} triple, so
// scanning one canonical size dir is sufficient (all-or-nothing per character).
const SCAN_DIR = join(PROJECT_ROOT, 'static/assets/characters/side');
const OUT = join(PROJECT_ROOT, 'src/lib/data/newfitAvatars.ts');

const SUFFIX = '-newfit.webp';

const files = await readdir(SCAN_DIR);
const slugs = files
	.filter((f) => f.endsWith(SUFFIX))
	.map((f) => f.slice(0, -SUFFIX.length))
	.sort();
// Base avatars are also authored as all-or-nothing {full,circle,side} triples;
// the same canonical size dir answers "does this character have avatars at all".
const available = files
	.filter((f) => f.endsWith('.webp') && !f.endsWith(SUFFIX))
	.map((f) => f.slice(0, -'.webp'.length))
	.sort();

const body = `// GENERATED by scripts/generate-newfit.js — do not edit by hand.
// Regenerate after adding/removing avatar assets: npm run generate-newfit

// Character slugs that have an alternate "-newfit" avatar (new-skin outfit).
export const NEWFIT_AVATARS: ReadonlySet<string> = new Set([
${slugs.map((s) => `\t'${s}'`).join(',\n')}
]);

// Character slugs that have base avatar assets at all (travelers etc. don't).
export const AVAILABLE_AVATARS: ReadonlySet<string> = new Set([
${available.map((s) => `\t'${s}'`).join(',\n')}
]);
`;

await writeFile(OUT, body, 'utf8');
console.log(
	`generate-newfit: wrote ${slugs.length} newfit + ${available.length} available slugs → ${OUT.replace(PROJECT_ROOT + '/', '')}`
);
