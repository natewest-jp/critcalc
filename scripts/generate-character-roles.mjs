/**
 * scripts/generate-character-roles.mjs
 *
 * Generates src/lib/data/characterRoles.generated.ts — editorial Imaginarium
 * Theater roles (Position + Function) per character, keyed by internal id,
 * sourced from docs/library/game/genshin-character-roles.csv.
 *
 * Roles are EDITORIAL (hand-sourced from Genshin's classification), so they
 * live outside the derive-only capabilities layer and off the shared character
 * index; the Team Builder joins this sidecar by id. Names are reconciled to
 * roster ids at build time — the report below flags anything to review.
 *
 * Imports the shared pure parser via type stripping (Node ≥22.18, .nvmrc);
 * parseRolesCsv.ts must stay free of runtime imports.
 *
 * Run after editing the CSV (e.g. a new character gets a role pass):
 *   npm run generate-character-roles
 * Also chained into predev/prebuild; drift-guarded by characterRoles.test.ts.
 */

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { parseRolesCsv, normalizeName } from '../src/lib/data/parseRolesCsv.ts';

const PROJECT_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CHARACTERS_DIR = join(PROJECT_ROOT, 'src/lib/data/characters');
const CSV = join(PROJECT_ROOT, 'docs/library/game/genshin-character-roles.csv');
const OUT = join(PROJECT_ROOT, 'src/lib/data/characterRoles.generated.ts');

// name/displayName → id from the character JSONs (blank.json is a slot
// placeholder, never a real character — exclude it).
const files = (await readdir(CHARACTERS_DIR))
	.filter((f) => f.endsWith('.json') && f !== 'blank.json')
	.sort();

const nameToId = new Map();
const rosterIds = [];
for (const file of files) {
	const data = JSON.parse(await readFile(join(CHARACTERS_DIR, file), 'utf8'));
	if (!data.id) continue;
	rosterIds.push(data.id);
	// displayName first so the fuller `name` wins on any collision.
	if (data.displayName) nameToId.set(normalizeName(data.displayName), data.id);
	if (data.name) nameToId.set(normalizeName(data.name), data.id);
}

const csvText = await readFile(CSV, 'utf8');
const { roles, unmapped } = parseRolesCsv(csvText, nameToId);

// --- Reconciliation report -------------------------------------------------
if (unmapped.length) {
	console.warn(
		`[generate-character-roles] ${unmapped.length} CSV name(s) did not map to a roster id (review — typo or CSV leads the roster):`
	);
	for (const n of unmapped) console.warn(`  · ${n}`);
}
const uncovered = rosterIds.filter((id) => !roles[id]).sort();
if (uncovered.length) {
	console.warn(
		`[generate-character-roles] ${uncovered.length} roster character(s) have no role — left unclassified (fine for pre-release/never-featured):`
	);
	for (const id of uncovered) console.warn(`  · ${id}`);
}
console.log(
	`[generate-character-roles] mapped ${Object.keys(roles).length}/${rosterIds.length} roster characters`
);

// --- Serialize (keyed by id, sorted, one entry per line for readable diffs) -
const ids = Object.keys(roles).sort();
const lines = ids.map((id) => `\t${JSON.stringify(id)}: ${JSON.stringify(roles[id])}`);

const output = `// Generated by scripts/generate-character-roles.mjs — do not edit by hand.
// Editorial Imaginarium Theater roles (Position + Function) for ${ids.length} characters,
// sourced from docs/library/game/genshin-character-roles.csv — Genshin's IT
// table plus documented editorial amendments (divergence rule: only when a
// derived capability proves the official table under-reports; see
// docs/curation/capability-sweep.md). Amended rows: Fischl +Support
// (Hexerei Secret Rite team ATK/EM), Rosaria +Support (Shadow Samaritan
// team crit share) — Nate, 2026-07-28.
import type { CharacterRoles } from '$lib/types/character';

export const characterRoles: Record<string, CharacterRoles> = {
${lines.join(',\n')}
};
`;

// Write only when content changed to avoid pointless dev-server invalidation.
let previous = null;
try {
	previous = await readFile(OUT, 'utf8');
} catch {
	// first generation
}
if (previous !== output) {
	await writeFile(OUT, output);
	console.log(`[generate-character-roles] wrote ${ids.length} entries to ${OUT}`);
} else {
	console.log(`[generate-character-roles] up to date (${ids.length} entries)`);
}
