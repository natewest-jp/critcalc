/**
 * scripts/generate-game-names.mjs
 *
 * Generates src/lib/data/gameNames.generated.ts: the game's own names for
 * every character, weapon, and artifact set the site carries, in each locale
 * besides English, read from the installed genshin-db. English names stay in
 * the data files; `$lib/i18n/gameNames` picks one for the page's language.
 *
 *   node scripts/generate-game-names.mjs
 *
 * Chained into predev and prebuild, so a genshin-db bump or a new character
 * reaches the table without a step to remember. `gameNames.test.ts` fails when
 * a new character, weapon, or set has no name in a locale.
 *
 * A name is taken only when genshin-db's English name is exactly ours, so its
 * autocomplete can't hand back a neighbour. The Travelers have no entry of
 * their own there (only Aether and Lumine), so each is 旅人 with its element's
 * one-character name, 旅人（風）, as the existing draft names the Traveler.
 * Game8 and Altema write 主人公(風) instead (an open question in
 * `docs/text/terms-ja.md`). The placeholder Blank is not a game character.
 *
 * Two small tables ride along, read off each character's genshin-db entry:
 * region names (keyed by the corpus's English region; "Other" is ours, not
 * the game's) and weapon-type names (keyed by our weapon id). English gets a
 * weapon-type table too, since the corpus stores only the id ("polearm").
 */

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DATA = join(ROOT, 'src/lib/data');
const OUT = join(DATA, 'gameNames.generated.ts');
const gdb = createRequire(import.meta.url)('genshin-db');

/** Our locale → genshin-db's language. */
const LOCALES = { ja: 'Japanese', zh: 'ChineseSimplified' };
/** Only the weapon types need English from genshin-db. */
const WITH_ENGLISH = { en: 'English', ...LOCALES };
const NOT_IN_GAME = new Set(['blank']);

async function corpus(dir) {
	const files = (await readdir(join(DATA, dir))).filter((f) => f.endsWith('.json')).sort();
	return Promise.all(
		files.map(async (f) => JSON.parse(await readFile(join(DATA, dir, f), 'utf8')))
	);
}

const english = { queryLanguages: [gdb.Language.English] };

/** genshin-db's name in `language` for our English name, or null. */
function lookup(folder, name, language) {
	const en = gdb[folder](name, english);
	if (!en || en.name !== name) return null;
	return gdb[folder](name, { ...english, resultLanguage: gdb.Language[language] })?.name || null;
}

function travelerName(element, language) {
	const el = gdb.elements(element, { ...english, resultLanguage: gdb.Language[language] })?.name;
	// TODO: data gap — genshin-db's elements carry no Chinese; zh waits for its term list.
	if (!el || language !== 'Japanese') return null;
	return `旅人（${el}）`;
}

const characters = await corpus('characters');
const weapons = await corpus('weapons');
const artifacts = await corpus('artifacts');

const tables = {};
const gaps = [];
for (const [locale, language] of Object.entries(WITH_ENGLISH)) {
	const t = { character: {}, weapon: {}, artifact: {}, region: {}, weaponType: {} };
	tables[locale] = t;
	// Region and weapon type, from every character genshin-db knows by our name.
	for (const c of characters) {
		if (NOT_IN_GAME.has(c.id) || c.id.startsWith('traveler_')) continue;
		const en = gdb.characters(c.name, english);
		if (!en || en.name !== c.name) continue;
		const here = gdb.characters(c.name, { ...english, resultLanguage: gdb.Language[language] });
		if (c.weapon && here?.weaponText) t.weaponType[c.weapon] ??= here.weaponText;
		if (locale !== 'en' && c.region && en.region === c.region && here?.region)
			t.region[c.region] ??= here.region;
	}
	if (locale === 'en') continue;
	for (const c of characters) {
		if (NOT_IN_GAME.has(c.id)) continue;
		const name = c.id.startsWith('traveler_')
			? travelerName(c.element[0].toUpperCase() + c.element.slice(1), language)
			: lookup('characters', c.name, language);
		if (name) t.character[c.id] = name;
		else gaps.push(`${locale} character ${c.id}`);
	}
	for (const [kind, list, folder] of [
		['weapon', weapons, 'weapons'],
		['artifact', artifacts, 'artifacts']
	])
		for (const x of list) {
			const name = lookup(folder, x.name, language);
			if (name) t[kind][x.id] = name;
			else gaps.push(`${locale} ${kind} ${x.id}`);
		}
}

const version = JSON.parse(
	await readFile(join(ROOT, 'node_modules/genshin-db/package.json'), 'utf8')
).version;
const body = `// Generated by scripts/generate-game-names.mjs from genshin-db ${version} — do not edit by hand.
// The game's names in each locale besides English (and English weapon types);
// read through $lib/i18n/gameNames.

export const GAME_NAMES: Record<
	string,
	{
		character: Record<string, string>;
		weapon: Record<string, string>;
		artifact: Record<string, string>;
		region: Record<string, string>;
		weaponType: Record<string, string>;
	}
> = ${JSON.stringify(tables, null, '\t')};
`;
await writeFile(OUT, body);
console.log(
	`wrote ${OUT}: ${Object.entries(tables)
		.map(
			([l, t]) =>
				`${l} ${Object.keys(t.character).length} characters, ${Object.keys(t.region).length} regions, ${Object.keys(t.weaponType).length} weapon types`
		)
		.join(', ')}`
);
// The Chinese Travelers are a known gap (above); anything else is news.
for (const g of gaps.filter((g) => !/^zh character traveler_/.test(g)))
	console.warn(`  ! no name: ${g}`);
