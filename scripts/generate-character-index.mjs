/**
 * scripts/generate-character-index.mjs
 *
 * Generates src/lib/data/characterIndex.generated.ts — a lightweight eager
 * index of every character JSON in src/lib/data/characters/. The index holds
 * the scalar identity fields plus derived capability summaries
 * (CharacterIndexEntry); full payloads are code-split and lazy-loaded via
 * src/lib/data/characterData.ts.
 *
 * Imports TypeScript modules directly (native type stripping — Node ≥22.18,
 * pinned by .nvmrc); the imported modules must stay free of runtime imports.
 *
 * Run after the (external) character generator updates the JSONs:
 *   npm run generate-character-index
 * Also chained into predev/prebuild so the committed index can't drift.
 * Drift is additionally guarded by src/lib/data/characterIndex.test.ts.
 *
 * One entry per line for readable diffs (same pattern as generate-stars.js);
 * the output file is .prettierignore'd.
 */

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
	collectGatedReactions,
	deriveCharacterCapabilities,
	summarizeCapabilities
} from '../src/lib/capabilities/deriveCapabilities.ts';
import {
	artifactShredSources,
	characterShredSources
} from '../src/lib/capabilities/shredSources.ts';
import { deriveCoverage, encodeCoverage } from '../src/lib/coverage/deriveCoverage.ts';
import { isCurated } from '../src/lib/utils/characterLint.ts';
import { declaredCastTokens, hasPlungeFrames } from '../src/lib/utils/castTokens.ts';

const PROJECT_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CHARACTERS_DIR = join(PROJECT_ROOT, 'src/lib/data/characters');
const OUT = join(PROJECT_ROOT, 'src/lib/data/characterIndex.generated.ts');
const ARTIFACTS_DIR = join(PROJECT_ROOT, 'src/lib/data/artifacts');
const SHRED_OUT = join(PROJECT_ROOT, 'src/lib/data/shredSources.generated.ts');

// Field order matters only for diff stability — keep in sync with
// CharacterIndexEntry in src/lib/types/character.ts.
const INDEX_FIELDS = [
	'id',
	'name',
	'displayName',
	'element',
	'weapon',
	'gender',
	'affiliation',
	'region',
	'rarity',
	'release',
	'noConstellations',
	'factions',
	'enablesReactions'
];

const files = (await readdir(CHARACTERS_DIR)).filter((f) => f.endsWith('.json')).sort();

const entries = [];
const shredRows = [];
for (const file of files) {
	const data = JSON.parse(await readFile(join(CHARACTERS_DIR, file), 'utf8'));
	if (!data.id) {
		console.warn(`[generate-character-index] skipping ${file}: no id`);
		continue;
	}
	const entry = {};
	for (const field of INDEX_FIELDS) {
		if (data[field] !== undefined) entry[field] = data[field];
	}
	entry.curated = isCurated(data);
	// The E/Q entry tokens this character can perform. Eager because the notation
	// editor lints against it on every keystroke and cannot wait for a lazy
	// payload — the same reason element/weapon are eager for the token tinting.
	entry.casts = declaredCastTokens(data);
	entry.plunge = hasPlungeFrames(data);
	const capabilities = deriveCharacterCapabilities(data).capabilities;
	entry.caps = summarizeCapabilities(capabilities);
	shredRows.push(...characterShredSources(data.id, data.displayName ?? data.name, capabilities));
	// The coverage strip, one state character per segment (deriveCoverage.ts,
	// COVERAGE_SEGMENTS order) — eager so the /coverage list, the announcement
	// banner and the TB's uncurated bucket can read it without the payloads.
	entry.coverage = encodeCoverage(deriveCoverage(data));
	const gated = collectGatedReactions(data);
	if (gated.length > 0) entry.gatedReactions = gated;
	entries.push(entry);
}

const lines = entries.map((e) => `\t${JSON.stringify(e)}`);

// The characters "in the works": kits with no frame data (the coverage strip's
// normal-attack timing reads missing — the FRAMELESS_EXEMPT class, minus the
// planner's `blank` slot). A SEPARATE export so the landing's announcement can
// import it without pulling the whole index into that bundle.
const inTheWorks = entries
	.filter((e) => e.id !== 'blank' && e.coverage[0] === 'm')
	.map((e) => e.displayName);

const output = `// Generated by scripts/generate-character-index.mjs — do not edit by hand.
// Lightweight identity index of all ${entries.length} character JSONs in ./characters/.
// Full payloads load lazily via ./characterData.ts.
import type { CharacterIndexEntry } from '$lib/types/character';

export const characterIndex: CharacterIndexEntry[] = [
${lines.join(',\n')}
];

/** Display names of the frameless characters — read by the landing's
 *  announcement ($lib/landing/announcements.ts). */
export const inTheWorks: string[] = ${JSON.stringify(inTheWorks)};
`;

// Every RES shred, DEF shred and DEF ignore in the data — the Visualizers'
// DEF & RES sources (2026-10-06). A separate module so the instrument does not
// pull the index, and the index does not carry the amounts.
const artifactFiles = (await readdir(ARTIFACTS_DIR)).filter((f) => f.endsWith('.json')).sort();
for (const file of artifactFiles) {
	shredRows.push(
		...artifactShredSources(JSON.parse(await readFile(join(ARTIFACTS_DIR, file), 'utf8')))
	);
}
const shredOutput = `// Generated by scripts/generate-character-index.mjs — do not edit by hand.
// Every shred and DEF ignore in the character and artifact data
// ($lib/capabilities/shredSources.ts). Read by the Visualizers' DEF & RES.
import type { ShredSource } from '$lib/capabilities/shredSources';

export const shredSources: ShredSource[] = [
${shredRows.map((r) => `\t${JSON.stringify(r)}`).join(',\n')}
];
`;

// Write only when content changed to avoid pointless dev-server invalidation.
async function writeIfChanged(path, text, what) {
	let previous = null;
	try {
		previous = await readFile(path, 'utf8');
	} catch {
		// first generation
	}
	if (previous !== text) {
		await writeFile(path, text);
		console.log(`[generate-character-index] wrote ${what} to ${path}`);
	} else {
		console.log(`[generate-character-index] up to date (${what})`);
	}
}
await writeIfChanged(OUT, output, `${entries.length} entries`);
await writeIfChanged(SHRED_OUT, shredOutput, `${shredRows.length} shred sources`);
