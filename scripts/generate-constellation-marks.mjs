import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// Extracts the C0–C6 CONSTELLATION GLYPHS from the SVGs Nate cut in
// static/assets/constellations/, so the site renders them as inline geometry
// like every other symbol it draws.
//
// WHY THEY EXIST AT ALL (⚓ NATE 2026-08-12): "what's stopping me from
// providing us a set of C0-C6 IBM Plex Sans as our own vector marks — it's a
// limited set, eliminates our need for fancy and shaky centering logic, and
// should look the same as the text anyway."
//
// He is right, and the thing it kills is worth naming: the bench card's C value
// used to be TEXT in a round chip, and centering text in a circle cost us a
// no-letter-spacing rule plus a −0.07em optical nudge, both measured at 8× in
// two engines, because a glyph's ink does not sit in the middle of its advance
// box and WebKit snaps text to whole pixels while boxes sit at sub-pixel
// precision. A path has no advance box, no bearings and no tracking residual,
// so all of that simply stops applying.
//
// ⚠ WHY THE SET IS UNIFORM AND MUST STAY THAT WAY: every glyph is exported at
// viewBox 0 0 26 16 with the ink spanning the full box (measured: x 0→25.1–26.0,
// y 0→15.88 in all seven). That is what makes them interchangeable — one box,
// centered once, and all seven land identically. Re-export the SET, never one
// glyph, or the odd one out will sit a fraction off and nobody will find it.
//
// WHAT IS STRIPPED: the source files carry `fill:white;fill-opacity:0.36`,
// which is the RESTING unset appearance baked into the artwork. The card has
// four states for this value (unset rest / unset hover / set / set hover), so
// the fill has to be currentColor and the ladder has to stay in CSS where it
// already lives. `fill-rule:nonzero` is kept — without it the counters in 0, 6
// and 8 fill solid.
//
// Auto-run by the predev/prebuild hooks. Manual: npm run generate-con-marks

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..');
const SRC_DIR = join(ROOT, 'static/assets/constellations');
const OUT = join(ROOT, 'src/lib/constellationMarks.generated.ts');

const LEVELS = [0, 1, 2, 3, 4, 5, 6];

/** Every `d` on the file's paths, in document order. */
function extractPaths(svg, file) {
	const ds = [...svg.matchAll(/<path\b[^>]*?\bd="([^"]+)"/g)].map((m) => m[1].trim());
	if (ds.length === 0) throw new Error(`${file}: no <path d="…"> found`);
	return ds;
}

function extractViewBox(svg, file) {
	const m = svg.match(/\bviewBox="([^"]+)"/);
	if (!m) throw new Error(`${file}: no viewBox`);
	return m[1].trim();
}

const paths = [];
let viewBox = null;

for (const level of LEVELS) {
	const file = `C${level}.svg`;
	const svg = await readFile(join(SRC_DIR, file), 'utf8');
	const vb = extractViewBox(svg, file);
	if (viewBox === null) viewBox = vb;
	// The whole value of the set is that one box fits all seven. A mismatch is
	// a re-export of a single glyph, which is the failure this guards.
	else if (vb !== viewBox) {
		throw new Error(`${file}: viewBox "${vb}" differs from "${viewBox}" — re-export the SET.`);
	}
	paths.push(extractPaths(svg, file));
}

const [, , vbW, vbH] = viewBox.split(/[\s,]+/).map(Number);

const out = `// GENERATED by scripts/generate-constellation-marks.mjs — do not edit.
//
// The C0–C6 constellation glyphs, set in IBM Plex Sans and cut to vector by
// Nate (source: static/assets/constellations/C*.svg). Rendered by
// $lib/components/ConMark.svelte, which owns the one <svg> wrapper they share.
//
// They are GEOMETRY rather than text on purpose: a path has no advance box, so
// centering one in a chip is centering a box in a box, with no bearings to
// correct and nothing for WebKit's whole-pixel glyph snapping to move. See the
// generator header for the rules that come with the set.

/** The box all seven share — the ink spans it fully in both axes. */
export const CON_MARK_VIEWBOX = '${viewBox}';

/** Width ÷ height of that box. The wrapper derives its width from this, so a
 *  caller only ever picks a HEIGHT (which is the glyph's cap height). */
export const CON_MARK_ASPECT = ${vbW} / ${vbH};

/** Constellation level (0–6) → its path data. */
export const CON_MARK_PATHS: readonly (readonly string[])[] = [
${paths.map((ds) => `\t[${ds.map((d) => JSON.stringify(d)).join(', ')}]`).join(',\n')}
];
`;

await writeFile(OUT, out);
console.log(`generate-constellation-marks: ${paths.length} glyphs → ${OUT}`);
