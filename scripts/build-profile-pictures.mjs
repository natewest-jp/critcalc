/**
 * scripts/build-profile-pictures.mjs
 *
 * The profile pictures (profiles and surfaces design §2.3), from Nate's
 * gitignored `assets-src/profile-pictures/` into `static/assets/profiles/`,
 * plus the manifest `src/lib/profilePictures.generated.ts`. Offline, like
 * `build-endgame-art.mjs`: the source is not in the repo, so the OUTPUT is
 * committed and the build never runs this.
 *
 *   node scripts/build-profile-pictures.mjs
 *
 * ⚓ Each file is named by a hash of its CONTENT (`{id}-{hash}.webp`):
 * `/assets/*` is cached forever (immutable, add-only), so a redrawn picture
 * must ship under a new name, and a content hash makes that automatic.
 *
 * ⚓ Theorycraft's picture is RESERVED (Nate 2026-10-22): it ships, because
 * Theorycraft shows it, but it is not in the list a real profile picks from,
 * and Theorycraft's own picture cannot be changed.
 */

import { createHash } from 'node:crypto';
import { mkdir, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve, parse } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'assets-src/profile-pictures');
const OUT = join(ROOT, 'static/assets/profiles');
const MANIFEST = join(ROOT, 'src/lib/profilePictures.generated.ts');

/** 🎛️ Edge in px: the bar's picture is at most ~40, a picker tile ~64, so
 *  128 covers 2× screens. The sources are 256. */
const PX = 128;
const QUALITY = 82;
const THEORYCRAFT = 'theorycraft';

/** "Hanachirusato%27s_Mask_Avatar" → the game's name, "Hanachirusato's Mask". */
function displayName(stem) {
	return decodeURIComponent(stem)
		.replace(/_Avatar$/, '')
		.replace(/_/g, ' ');
}

/** The id a profile record stores: lowercase, hyphenated, ASCII. */
function slug(name) {
	return name
		.toLowerCase()
		.replace(/&/g, 'and')
		.replace(/['’!]/g, '')
		.replace(/[^a-z0-9]+/g, '-')
		.replace(/^-|-$/g, '');
}

const files = (await readdir(SRC)).filter((f) => /\.(webp|png|jpe?g)$/i.test(f)).sort();
await rm(OUT, { recursive: true, force: true });
await mkdir(OUT, { recursive: true });

const pictures = [];
for (const file of files) {
	const name = displayName(parse(file).name);
	const id = slug(name);
	const buf = await sharp(join(SRC, file))
		.resize(PX, PX, { fit: 'cover' })
		.webp({ quality: QUALITY, alphaQuality: 80 })
		.toBuffer();
	const hash = createHash('sha256').update(buf).digest('hex').slice(0, 8);
	const out = `${id}-${hash}.webp`;
	await writeFile(join(OUT, out), buf);
	pictures.push({ id, name, url: `/assets/profiles/${out}` });
}

const tc = pictures.find((p) => p.id === THEORYCRAFT);
if (!tc) throw new Error(`no ${THEORYCRAFT} picture in ${SRC}`);
const choosable = pictures.filter((p) => p.id !== THEORYCRAFT);

const ts = `// Generated by scripts/build-profile-pictures.mjs — do not edit.

export type ProfilePicture = { id: string; name: string; url: string };

/** Theorycraft's own picture: reserved, never in the picker. */
export const THEORYCRAFT_PICTURE: ProfilePicture = ${JSON.stringify(tc)};

/** The pictures a real profile chooses from, in name order. */
export const PROFILE_PICTURES: readonly ProfilePicture[] = ${JSON.stringify(choosable, null, '\t')};
`;
await writeFile(MANIFEST, ts);
console.log(`${choosable.length} choosable + Theorycraft → static/assets/profiles/`);
