<h1>Privacy</h1>

<p class="lede">
	The short version: critcalc keeps <strong>nothing</strong> about you on a server. No accounts, no tracking,
	no cookies.
</p>

<h2>Your data stays in your browser</h2>
<p>
	Everything you set in critcalc — your roster and constellations, weapon and artifact loadouts,
	saved rotations, and preferences — is stored only in your own browser, using its built-in
	<code>localStorage</code>. None of it is ever sent to or stored on a server, because there is no
	server to send it to: critcalc is a static site with no backend, no database, and no accounts.
</p>
<p>
	That also means your data is per-device and per-browser. To move it, use
	<strong>Settings → Your data → Export</strong> to download a backup file, and
	<strong>Import</strong> it elsewhere. You can wipe everything at any time from the same place, or by
	clearing this site's data in your browser settings.
</p>

<h2>No tracking</h2>
<p>
	critcalc sets no cookies and runs no analytics, advertising, or third-party tracking scripts in
	your browser. Nothing here follows you around the web.
</p>
<p>
	Like any website, the host that serves these pages (Cloudflare Pages) processes standard technical
	request data — such as your IP address — purely to deliver the site and protect it from abuse.
	critcalc itself neither collects nor retains any of it.
</p>

<h2>External links</h2>
<p>
	Some pages link out to community resources such as gcsim and Keqing Mains. Those sites have their
	own privacy practices, which this policy doesn't cover.
</p>

<h2>Changes</h2>
<p>
	If this ever changes — for example, if an optional, privacy-respecting analytics measure is added
	— this page will say so plainly before it does.
</p>
